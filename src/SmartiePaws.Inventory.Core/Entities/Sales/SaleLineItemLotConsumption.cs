using SmartiePaws.Inventory.Core.Entities.Purchasing;

namespace SmartiePaws.Inventory.Core.Entities.Sales;

/// <summary>
/// Records exactly which <see cref="PurchaseOrderLineItem"/> (FIFO lot) a
/// <see cref="SaleLineItem"/>'s quantity was drawn from. A single line item's quantity can span
/// more than one PurchaseOrderLineItem if the oldest lot didn't have enough units left to cover
/// the full sale on its own -- this table is what makes that possible while keeping an exact,
/// auditable cost trail for every unit sold. Immutable once written, with no independent
/// timestamps of its own.
/// </summary>
public class SaleLineItemLotConsumption
{
  /// <summary>
  /// Primary key. Generated by Postgres (<c>gen_random_uuid()</c>) on insert.
  /// </summary>
  public Guid Id { get; set; }

  /// <summary>
  /// Foreign key to the sale line this consumption record belongs to.
  /// </summary>
  public Guid SaleLineItemId { get; set; }

  /// <summary>
  /// Navigation to the sale line. Only populated when explicitly requested.
  /// </summary>
  public SaleLineItem SaleLineItem { get; set; } = null!;

  /// <summary>
  /// Foreign key to the specific restock batch (lot) the consumed units came from.
  /// </summary>
  public Guid PurchaseOrderLineItemId { get; set; }

  /// <summary>
  /// Navigation to the lot. Only populated when explicitly requested.
  /// </summary>
  public PurchaseOrderLineItem PurchaseOrderLineItem { get; set; } = null!;

  /// <summary>
  /// How many units of the line item's sale came from this particular lot. If a line's full
  /// quantity came from one lot, there's exactly one of these rows per line; if it spanned lots,
  /// there's one row per lot touched.
  /// </summary>
  public int QuantityConsumed { get; set; }

  /// <summary>
  /// A copy of that lot's <see cref="PurchaseOrderLineItem.UnitCost"/> at the moment of
  /// consumption. The lot's UnitCost itself never changes, so this is mostly a convenience/audit
  /// copy -- it means this table alone has everything needed to compute COGS for a sale without
  /// joining back to PurchaseOrderLineItem every time.
  /// </summary>
  public decimal UnitCost { get; set; }
}
